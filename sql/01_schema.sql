create schema if not exists core;     -- dados do Instituto (inclui dados pessoais)
create schema if not exists acesso;   -- auditoria, feedback e autorizações

-- ---------------------------------------------------------------- características
create table if not exists core.dimensao (
    id_dimensao  bigint generated by default as identity primary key,
    nome         text not null unique,
    sigla        text
);

create table if not exists core.categoria_atividade (
    id_categoria bigint generated by default as identity primary key,
    nome         text not null unique
);

create table if not exists core.comunidade (
    id_comunidade bigint generated by default as identity primary key,
    nome          text not null unique
);

create table if not exists core.item_doacao (
    id_item_doacao bigint generated by default as identity primary key,
    nome           text not null unique,
    tipo           text
);

-- ---------------------------------------------------------------- parceiros e metas (ainda sem fonte de dados)
create table if not exists core.financiador (
    id_financiador       bigint generated by default as identity primary key,
    nome                 text not null,
    descricao            text,
    data_inicio_parceria date not null
);

create table if not exists core.projeto (
    id_projeto     bigint generated by default as identity primary key,
    id_financiador bigint not null references core.financiador (id_financiador),
    nome           text not null,
    data_inicio    date not null,
    data_fim       date,
    constraint ck_projeto_datas check (data_fim is null or data_fim >= data_inicio)
);

create table if not exists core.formador (
    id_formador  bigint generated by default as identity primary key,
    nome         text not null,
    qualificacao text
);

create table if not exists core.rubrica (
    id_rubrica  bigint generated by default as identity primary key,
    id_dimensao bigint not null references core.dimensao (id_dimensao),
    descricao   text not null
);

create table if not exists core.acao_unica (
    id_acao    bigint generated by default as identity primary key,
    id_rubrica bigint not null references core.rubrica (id_rubrica),
    acao       text not null
);

create table if not exists core.indicador (
    id_indicador    bigint generated by default as identity primary key,
    id_dimensao     bigint not null references core.dimensao (id_dimensao),
    id_projeto      bigint not null references core.projeto (id_projeto),
    tipo            text not null,
    descricao       text not null,
    nome_resumido   text not null,
    peso            numeric(5,2),
    especificidades text,
    formula         text,
    nivel_minimo    text not null default 'publico' check (nivel_minimo in ('publico', 'pesquisador', 'admin'))
);

create table if not exists core.projeto_dimensao (
    id_projeto  bigint not null references core.projeto (id_projeto),
    id_dimensao bigint not null references core.dimensao (id_dimensao),
    primary key (id_projeto, id_dimensao)
);
create table if not exists core.projeto_rubrica (
    id_projeto bigint not null references core.projeto (id_projeto),
    id_rubrica bigint not null references core.rubrica (id_rubrica),
    primary key (id_projeto, id_rubrica)
);
create table if not exists core.projeto_acao_unica (
    id_projeto bigint not null references core.projeto (id_projeto),
    id_acao    bigint not null references core.acao_unica (id_acao),
    primary key (id_projeto, id_acao)
);

-- ---------------------------------------------------------------- atividades
create table if not exists core.atividade (
    id_atividade bigint generated by default as identity primary key,
    nome         text not null unique,
    id_dimensao  bigint references core.dimensao (id_dimensao),
    id_categoria bigint references core.categoria_atividade (id_categoria)
);

create table if not exists core.oferta (
    id_oferta         bigint generated by default as identity primary key,
    id_atividade      bigint not null references core.atividade (id_atividade),
    id_dimensao       bigint references core.dimensao (id_dimensao),
    id_categoria      bigint references core.categoria_atividade (id_categoria),
    turma             text,
    data_inicio       date not null,
    data_fim          date not null,
    id_projeto        bigint references core.projeto (id_projeto),
    id_formador       bigint references core.formador (id_formador),
    id_rubrica        bigint references core.rubrica (id_rubrica),
    id_indicador      bigint references core.indicador (id_indicador),
    local             text,
    descricao         text,
    foto_coletiva     text,
    link_documentacao text,
    constraint ck_oferta_datas check (data_fim >= data_inicio)
);
alter table core.oferta add column if not exists id_dimensao bigint references core.dimensao (id_dimensao);
alter table core.oferta add column if not exists id_categoria bigint references core.categoria_atividade (id_categoria);
create unique index if not exists uq_oferta on core.oferta (id_atividade, coalesce(turma, ''), data_inicio, data_fim);
create index if not exists ix_oferta_atividade on core.oferta (id_atividade);
create index if not exists ix_oferta_datas on core.oferta (data_inicio, data_fim);

-- ---------------------------------------------------------------- pessoas e território (DADOS PESSOAIS)
create table if not exists core.familia (
    id_familia       bigint primary key,                 -- código original da planilha
    responsavel_nome text,
    endereco         text,
    numero           text,
    complemento      text,
    endereco_kobo    text,
    id_comunidade    bigint references core.comunidade (id_comunidade),
    bairro           text,
    zona             text,
    latitude         numeric(9,6),
    longitude        numeric(9,6)
);
create index if not exists ix_familia_comunidade on core.familia (id_comunidade);

create table if not exists core.morador (
    id_morador      bigint generated by default as identity primary key,
    codigo_morador  text not null unique,                -- formato "ID.seq" (ex.: 12.3)
    id_familia      bigint,                              -- sem FK por enquanto: há moradores de famílias ainda não cadastradas (Q-06c)
    nome            text,
    sexo            text,
    data_nascimento date,
    cpf             varchar(11),                         -- CPF repetido existe na base (Q-03d): índice comum, sem unicidade
    telefone        text,
    id_comunidade   bigint references core.comunidade (id_comunidade),
    bairro          text,
    zona            text,
    ciclo           smallint,
    ipm             smallint,
    status          text,
    grupo           smallint,
    constraint ck_morador_cpf check (cpf is null or cpf ~ '^[0-9]{11}$')
);
alter table core.morador add column if not exists id_comunidade bigint references core.comunidade (id_comunidade);
alter table core.morador add column if not exists bairro text;
alter table core.morador add column if not exists zona text;
create index if not exists ix_morador_familia on core.morador (id_familia);
create index if not exists ix_morador_cpf on core.morador (cpf);
create index if not exists ix_morador_comunidade on core.morador (id_comunidade);

create table if not exists core.participante (
    id_participante bigint generated by default as identity primary key,
    id_morador      bigint unique references core.morador (id_morador),
    nome            text,
    origem          text not null check (origem in ('cadastro', 'externo'))
);

create table if not exists core.participacao (
    id_participacao bigint generated by default as identity primary key,
    id_oferta       bigint not null references core.oferta (id_oferta),
    id_participante bigint not null references core.participante (id_participante),
    tipo            text not null,
    doacao          boolean not null default false,
    id_item_doacao  bigint references core.item_doacao (id_item_doacao),
    cesta_basica    boolean not null default false,
    id_comunidade   bigint references core.comunidade (id_comunidade),
    constraint uq_participacao unique (id_oferta, id_participante, tipo)
);
create index if not exists ix_participacao_participante on core.participacao (id_participante);
create index if not exists ix_participacao_oferta on core.participacao (id_oferta);
create index if not exists ix_participacao_comunidade on core.participacao (id_comunidade);

create table if not exists core.avaliacao (
    id_avaliacao            bigint generated by default as identity primary key,
    id_oferta               bigint references core.oferta (id_oferta),
    id_participante         bigint references core.participante (id_participante),
    id_dimensao             bigint references core.dimensao (id_dimensao),
    evento                  text,
    data_formacao           date,
    data_formacao_texto     text,
    nome_avaliador          text,
    q01_aprendizado         smallint,
    q02_organizacao         smallint,
    q03_professores         smallint,
    q04_recomendacao        smallint,
    q05_infraestrutura      smallint,
    q06_duracao             smallint,
    q07_informacoes_previas smallint,
    q08_material            smallint,
    q09_lanche              smallint,
    turno_preferido         text,
    turno_manha             boolean,
    turno_tarde             boolean,
    turno_noite             boolean,
    turno_fim_semana        boolean,
    intencao                text,
    int_trabalhar_area      boolean,
    int_primeiro_emprego    boolean,
    int_mudar_area          boolean,
    int_crescer_carreira    boolean,
    int_abrir_negocio       boolean,
    int_renda_extra         boolean,
    int_interesse_pessoal   boolean,
    int_feiras_eventos      boolean,
    int_indeciso            boolean,
    int_outro               boolean,
    outro_texto             text,
    elogios_texto           text,
    melhorias_texto         text,
    nota_geral              numeric(4,2),
    formato                 text,
    categoria_elogios       text,
    categoria_melhorias     text
);
alter table core.avaliacao add column if not exists q09_lanche smallint;
create index if not exists ix_avaliacao_participante on core.avaliacao (id_participante);
create index if not exists ix_avaliacao_oferta on core.avaliacao (id_oferta);
create index if not exists ix_avaliacao_dimensao on core.avaliacao (id_dimensao);

-- ---------------------------------------------------------------- controle da carga
create table if not exists core.carga_info (
    id          smallint primary key default 1 check (id = 1),   -- uma linha só: a carga atual
    carregado_em timestamptz not null default now(),
    origem      text,
    mascarado   boolean not null default false,                  -- true = identificações trocadas por dados fictícios
    resumo      jsonb
);
create table if not exists core.carga_qualidade (
    id          text primary key,
    problema    text not null,
    ocorrencias bigint not null,
    base        bigint,
    percentual  numeric(5,1)
);

-- ---------------------------------------------------------------- acesso, auditoria e feedback
create table if not exists acesso.log_acesso (
    id_log   bigint generated by default as identity primary key,
    momento  timestamptz not null default now(),
    email    text,
    nivel    text not null,
    acao     text not null,
    recurso  text,
    filtros  jsonb,
    linhas   integer
);
create table if not exists acesso.feedback (
    id_feedback bigint generated by default as identity primary key,
    momento     timestamptz not null default now(),
    nome        text,
    tipo        text,
    pagina      text,
    texto       text not null,
    filtros     jsonb
);
create table if not exists acesso.acesso_pesquisador (
    id_pesquisador  bigint generated by default as identity primary key,
    email           text not null unique,
    nome            text not null,
    instituicao     text,
    finalidade      text,
    status          text not null default 'pendente' check (status in ('pendente', 'aprovado', 'revogado')),
    termo_aceito_em timestamptz,
    aprovado_por    text,
    expira_em       timestamptz
);

-- ---------------------------------------------------------------- SEGURANÇA
do $$
declare t record;
begin
    for t in select schemaname, tablename from pg_tables where schemaname in ('core', 'acesso') loop
        execute format('alter table %I.%I enable row level security', t.schemaname, t.tablename);
    end loop;
    if exists (select 1 from pg_roles where rolname = 'anon') then
        execute 'revoke all on all tables in schema core, acesso from anon';
        execute 'revoke usage on schema core, acesso from anon';
    end if;
    if exists (select 1 from pg_roles where rolname = 'authenticated') then
        execute 'revoke all on all tables in schema core, acesso from authenticated';
        execute 'revoke usage on schema core, acesso from authenticated';
    end if;
end $$;
